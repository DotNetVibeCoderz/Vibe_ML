    private static ComplexNdArray X()
    {
        var d = new Complex[20];
        for (var i = 0; i < 4; i++)
            for (var j = 0; j < 5; j++)
                d[i * 5 + j] = new Complex((i * 7 + j * 3) % 5, (i + 2 * j) % 3);
        return new ComplexNdArray(d, 4, 5);
    }

    private static void Check(double[] expected, ComplexNdArray actual)
    {
        var a = actual.ToArray();
        for (var k = 0; k < a.Length; k++)
        {
            Assert.True(Math.Abs(a[k].Real - expected[2 * k]) < 1e-13, $"re {k}: {a[k].Real} vs {expected[2 * k]}");
            Assert.True(Math.Abs(a[k].Imaginary - expected[2 * k + 1]) < 1e-13, $"im {k}: {a[k].Imaginary} vs {expected[2 * k + 1]}");
        }
    }

    [Fact]
    public void FourierGaussian_MatchesScipy() => Check(Gauss, NdImage.FourierGaussian(X(), [1.2, 0.7]));

    [Fact]
    public void FourierUniform_MatchesScipy() => Check(Uniform, NdImage.FourierUniform(X(), [2.0, 3.0]));

    [Fact]
    public void FourierShift_MatchesScipy() => Check(Shift, NdImage.FourierShift(X(), [0.3, -1.4]));
}
