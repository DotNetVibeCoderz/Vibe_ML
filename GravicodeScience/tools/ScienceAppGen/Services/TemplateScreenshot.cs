using Avalonia;
using Avalonia.Controls;
using Avalonia.Controls.ApplicationLifetimes;
using Avalonia.Media.Imaging;
using Avalonia.Threading;
using Avalonia.VisualTree;
using ScienceAppGen.ViewModels;
using ScienceAppGen.Views;

namespace ScienceAppGen.Services;

/// <summary>
/// <c>ScienceAppGen --capture-template &lt;id&gt; &lt;folder&gt; [--work &lt;dir&gt;]</c>: shows the New Project
/// dialog with a template selected, then creates that project, builds and runs it in the real
/// shell, and renders both states to PNGs for the documentation.
/// </summary>
/// <remarks>
/// Nothing here is staged: the project is generated by <see cref="TemplateService.Create"/>, built
/// and run by <see cref="ProjectService"/> exactly as F5 does, and the output panel shows what the
/// program printed. No model is called, so no API key is needed. Content is rendered at a fixed
/// size so the images do not depend on the screen they were taken on. The project is left in
/// <c>--work</c> (default: a temporary folder) so it can be inspected afterwards.
/// </remarks>
public static class TemplateScreenshot
{
    /// <summary>True when the arguments ask for a template capture.</summary>
    public static bool IsRequested(string[] args) => args.Contains("--capture-template", StringComparer.OrdinalIgnoreCase);

    /// <summary>Runs the capture and shuts the application down.</summary>
    public static async Task RunAsync(string[] args, MainWindow window, ShellViewModel shell,
        IClassicDesktopStyleApplicationLifetime lifetime)
    {
        var index = Array.FindIndex(args, a => a.Equals("--capture-template", StringComparison.OrdinalIgnoreCase));
        var id = args[index + 1];
        var folder = Path.GetFullPath(args[index + 2]);
        var work = Array.FindIndex(args, a => a.Equals("--work", StringComparison.OrdinalIgnoreCase)) is var w and >= 0
            ? Path.GetFullPath(args[w + 1])
            : Path.Combine(Path.GetTempPath(), "ScienceAppGen-capture");
        Directory.CreateDirectory(folder);

        try
        {
            var template = TemplateService.Find(id) ?? throw new ArgumentException($"No template '{id}'.");
            var name = string.Concat(id.Split('-').Select(p => char.ToUpperInvariant(p[0]) + p[1..]));
            await Settle();

            // 1. The dialog, scrolled to the template and with it selected.
            var dialog = new NewProjectDialog(work);
            dialog.FindControl<TextBox>("NameBox")!.Text = name;
            var list = dialog.FindControl<ListBox>("TemplateList")!;
            dialog.Show(window);
            await Settle();
            list.SelectedItem = template;
            list.ScrollIntoView(template);
            await Settle();
            Save(dialog, folder, $"scienceappgen-{id}-dialog.png", dialog.Bounds.Width, dialog.Bounds.Height, wholeWindow: true);
            dialog.Close();

            // 2. The project, created, opened, built and run.
            var target = Path.Combine(work, name);
            if (Directory.Exists(target)) Directory.Delete(target, recursive: true);
            TemplateService.Create(template, target, name);
            shell.Projects.OpenProject(target);
            shell.LogsHeight = 440;                       // room for the program's output; not persisted
            shell.Editor.OpenFile(Path.Combine(target, "Program.cs"));
            shell.StatusMessage = "Buildingâ€¦";
            var build = await shell.Projects.BuildAsync();
            if (build.Succeeded)
            {
                shell.StatusMessage = "Runningâ€¦";
                var run = await shell.Projects.RunAsync();
                shell.StatusMessage = run.Succeeded ? "Run finished" : "Run failed";
            }
            else shell.StatusMessage = "Build failed";
            await Settle();
            Save(window, folder, $"scienceappgen-{id}-run.png", 1600, 1000);
        }
        catch (Exception ex)
        {
            shell.Logs.Error("capture", ex.ToString());
        }
        finally
        {
            lifetime.Shutdown();
        }
    }

    private static async Task Settle()
    {
        await Task.Delay(800);
        await Dispatcher.UIThread.InvokeAsync(() => { }, DispatcherPriority.Background);
    }

    private static void Save(Window window, string folder, string name, double width, double height, bool wholeWindow = false)
    {
        // A dialog is rendered whole: its content alone loses the window background, and text
        // drawn on a transparent surface comes out as outlines.
        var content = wholeWindow ? window : (Control)window.Content!;
        Layout(content, width, height);

        // The output panel follows its last line; at the capture size it has to be scrolled again,
        // and the new offset only applies on the next arrange.
        foreach (var scroller in content.GetVisualDescendants().OfType<ScrollViewer>().Where(s => s.Name == "Scroller"))
            scroller.ScrollToEnd();
        Layout(content, width, height);

        var scale = window.RenderScaling;
        using var bitmap = new RenderTargetBitmap(new PixelSize((int)(width * scale), (int)(height * scale)),
            new Vector(96 * scale, 96 * scale));
        bitmap.Render(content);
        bitmap.Save(Path.Combine(folder, name), new PngBitmapEncoderOptions());

        content.InvalidateMeasure();
    }

    private static void Layout(Control content, double width, double height)
    {
        content.Measure(new Size(width, height));
        content.Arrange(new Rect(0, 0, width, height));
    }
}
